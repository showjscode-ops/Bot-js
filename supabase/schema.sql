create table if not exists public.bot_users (
  telegram_id bigint primary key,
  first_name text not null default '',
  username text not null default '',
  language text check (language in ('id','en')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.force_join (
  id bigint generated by default as identity primary key,
  name text not null,
  invite_link text not null,
  chat_id text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists force_join_active_idx on public.force_join(active);
alter table public.bot_users enable row level security;
alter table public.force_join enable row level security;
