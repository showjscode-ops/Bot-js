-- 1. BOT USERS
CREATE TABLE IF NOT EXISTS public.bot_users (
    telegram_id BIGINT PRIMARY KEY,
    first_name TEXT NOT NULL DEFAULT '',
    username TEXT NOT NULL DEFAULT '',
    language TEXT CHECK (language IN ('id', 'en')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. FORCE JOIN
CREATE TABLE IF NOT EXISTS public.force_join (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    invite_link TEXT NOT NULL,
    chat_id TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. BOT ADMINS
CREATE TABLE IF NOT EXISTS public.bot_admins (
    telegram_id BIGINT PRIMARY KEY,
    added_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. VIP PACKAGES
CREATE TABLE IF NOT EXISTS public.vip_packages (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    price INTEGER NOT NULL CHECK (price >= 2000),
    invite_link TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 10,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. VIP COUPONS
CREATE TABLE IF NOT EXISTS public.vip_coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    discount_type TEXT NOT NULL DEFAULT 'percent'
        CHECK (discount_type IN ('percent', 'fixed')),
    discount_value INTEGER NOT NULL,
    package_id TEXT REFERENCES public.vip_packages(id),
    max_uses INTEGER,
    used_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. VIP ORDERS
CREATE TABLE IF NOT EXISTS public.vip_orders (
    order_id TEXT PRIMARY KEY,
    telegram_id BIGINT NOT NULL,
    package_id TEXT NOT NULL REFERENCES public.vip_packages(id),
    amount INTEGER NOT NULL,
    original_amount INTEGER NOT NULL,
    discount INTEGER NOT NULL DEFAULT 0,
    coupon_id BIGINT,
    status TEXT NOT NULL DEFAULT 'PENDING',
    cashi_order_id TEXT,
    checkout_url TEXT,
    gateway_data JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paid_at TIMESTAMPTZ
);

-- 7. BOT STATES
CREATE TABLE IF NOT EXISTS public.bot_states (
    telegram_id BIGINT PRIMARY KEY,
    state TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. MEDIA DRAFTS
CREATE TABLE IF NOT EXISTS public.media_drafts (
    id UUID PRIMARY KEY,
    admin_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'DRAFT',
    stage TEXT NOT NULL DEFAULT 'collect',
    media JSONB NOT NULL DEFAULT '[]'::JSONB,
    config JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 9. MEDIA LINKS
CREATE TABLE IF NOT EXISTS public.media_links (
    id TEXT PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    media JSONB NOT NULL,
    expires_at TIMESTAMPTZ,
    max_access INTEGER,
    access_count INTEGER NOT NULL DEFAULT 0,
    price INTEGER NOT NULL DEFAULT 0,
    required_groups JSONB NOT NULL DEFAULT '[]'::JSONB,
    allowed_users JSONB NOT NULL DEFAULT '[]'::JSONB,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 10. MEDIA ORDERS
CREATE TABLE IF NOT EXISTS public.media_orders (
    order_id TEXT PRIMARY KEY,
    telegram_id BIGINT NOT NULL,
    media_id TEXT NOT NULL REFERENCES public.media_links(id),
    amount INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING',
    cashi_order_id TEXT,
    checkout_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paid_at TIMESTAMPTZ
);

-- 11. BOT DONATIONS
CREATE TABLE IF NOT EXISTS public.bot_donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_id BIGINT NOT NULL,
    stars INTEGER NOT NULL,
    currency TEXT NOT NULL,
    payload TEXT,
    telegram_charge_id TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 12. INDEXES
CREATE INDEX IF NOT EXISTS force_join_active_idx
    ON public.force_join(active);

CREATE INDEX IF NOT EXISTS vip_orders_status_idx
    ON public.vip_orders(status);

CREATE INDEX IF NOT EXISTS media_drafts_admin_idx
    ON public.media_drafts(admin_id, status);

CREATE INDEX IF NOT EXISTS media_links_active_idx
    ON public.media_links(active);

CREATE INDEX IF NOT EXISTS media_links_created_idx
    ON public.media_links(created_at DESC);

CREATE INDEX IF NOT EXISTS media_orders_status_idx
    ON public.media_orders(status);

CREATE INDEX IF NOT EXISTS bot_users_created_idx
    ON public.bot_users(created_at DESC);

