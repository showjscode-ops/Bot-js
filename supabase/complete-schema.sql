-- Book keep bot schema. Run in Supabase SQL Editor.
create table if not exists public.bot_users (
 telegram_id bigint primary key, first_name text not null default '', username text not null default '',
 language text check(language in ('id','en')), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.force_join (
 id bigint generated by default as identity primary key, name text not null, invite_link text not null,
 chat_id text not null, active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.bot_admins (telegram_id bigint primary key, added_by bigint not null, created_at timestamptz not null default now());
create table if not exists public.vip_packages (
 id text primary key, name text not null, description text not null default '', price integer not null check(price>=2000),
 invite_link text not null, active boolean not null default true, sort_order integer not null default 10, created_at timestamptz not null default now()
);
create table if not exists public.vip_coupons (
 id bigint generated by default as identity primary key, code text unique not null,
 discount_type text not null default 'percent' check(discount_type in ('percent','fixed')), discount_value integer not null,
 package_id text references public.vip_packages(id), max_uses integer, used_count integer not null default 0,
 active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.vip_orders (
 order_id text primary key, telegram_id bigint not null, package_id text not null references public.vip_packages(id),
 amount integer not null, original_amount integer not null, discount integer not null default 0, coupon_id bigint,
 status text not null default 'PENDING', cashi_order_id text, checkout_url text, gateway_data jsonb,
 created_at timestamptz not null default now(), paid_at timestamptz
);
create table if not exists public.bot_states (telegram_id bigint primary key, state text not null, updated_at timestamptz not null default now());
create table if not exists public.media_drafts (
 id uuid primary key, admin_id bigint not null, status text not null default 'DRAFT', stage text not null default 'collect',
 media jsonb not null default '[]'::jsonb, config jsonb not null default '{}'::jsonb, created_at timestamptz not null default now()
);
create table if not exists public.media_links (
 id text primary key, owner_id bigint not null, title text not null, media jsonb not null,
 expires_at timestamptz, expires_minutes integer, max_access integer, access_count integer not null default 0,
 required_groups jsonb not null default '[]'::jsonb, allowed_users jsonb not null default '[]'::jsonb,
 active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.media_orders (
 order_id text primary key, telegram_id bigint not null, media_id text not null references public.media_links(id),
 amount integer not null, status text not null default 'PENDING', cashi_order_id text, checkout_url text,
 created_at timestamptz not null default now(), paid_at timestamptz
);
create table if not exists public.bot_donations (
 id bigint generated by default as identity primary key, telegram_id bigint not null, stars integer not null,
 currency text not null, payload text, telegram_charge_id text unique, created_at timestamptz not null default now()
);
create index if not exists force_join_active_idx on public.force_join(active);
create index if not exists vip_orders_status_idx on public.vip_orders(status);
create index if not exists media_drafts_admin_idx on public.media_drafts(admin_id,status);
