CREATE OR REPLACE FUNCTION public.claim_media_access(p_media_id TEXT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE updated_id TEXT;
BEGIN
 UPDATE public.media_links
 SET access_count = access_count + 1
 WHERE id = p_media_id AND active = TRUE
   AND (max_access IS NULL OR access_count < max_access)
   AND (expires_at IS NULL OR expires_at > NOW())
 RETURNING id INTO updated_id;
 IF updated_id IS NULL THEN RETURN jsonb_build_object('ok',FALSE); END IF;
 RETURN jsonb_build_object('ok',TRUE);
END; $$;
REVOKE ALL ON FUNCTION public.claim_media_access(TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_media_access(TEXT) TO service_role;
